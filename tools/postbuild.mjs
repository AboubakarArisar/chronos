// After `vite build`: writes dist/sw.js (offline support) with the list of core files to precache.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..'), DIST = path.join(ROOT, 'dist');
const all = [];
(function walk(dir) { for (const e of fs.readdirSync(dir, { withFileTypes: true })) { const p = path.join(dir, e.name); if (e.isDirectory()) walk(p); else all.push(path.relative(DIST, p).replace(/\\/g, '/')); } })(DIST);
// core = everything needed to start and use the globe; maps are fetched in the background after first load;
// art and music are cached as they are used
const core = all.filter(f => f !== 'sw.js' && !f.startsWith('assets/music/') && !f.startsWith('assets/art/') && !f.startsWith('d/b/') && !/\.map$/.test(f) && (!/\.woff2?$/.test(f) || /(cinzel|alegreya|manrope)-latin-/.test(f)));
const maps = all.filter(f => /^d\/b\/-?\d+\.json$/.test(f));
const version = crypto.createHash('sha1').update(all.map(f => f + fs.statSync(path.join(DIST, f)).size).join('|')).digest('hex').slice(0, 10);

const sw = `// Chronos service worker (generated by tools/postbuild.mjs). Cache first, so the app works offline after the first load.
const CACHE = 'chronos-${version}';
const CORE = ${JSON.stringify(core)};
const MAPS = ${JSON.stringify(maps)};
self.addEventListener('install', e => { e.waitUntil(caches.open(CACHE).then(async c => { await Promise.all(CORE.map(u => c.add(u).catch(() => {}))); }).then(() => self.skipWaiting())); });
self.addEventListener('activate', e => { e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith('chronos-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('message', e => { if (e.data === 'precache-maps') e.waitUntil(caches.open(CACHE).then(async c => { for (const u of MAPS) { if (!(await c.match(u))) await c.add(u).catch(() => {}); } })); });
self.addEventListener('fetch', e => {
  const req = e.request, url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== location.origin) return; // Wikipedia requests go straight to the network
  e.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const hit = await cache.match(req, { ignoreSearch: true }) || (req.mode === 'navigate' && url.pathname.endsWith('/') ? await cache.match('index.html') : null);
    if (hit) return hit;
    try {
      const res = await fetch(req);
      if (res.status === 200 && res.type === 'basic') cache.put(req, res.clone()).catch(() => {});
      else if (res.status === 206) fetch(url.href).then(full => { if (full.status === 200) cache.put(url.href, full).catch(() => {}); }).catch(() => {}); // audio asked for a range: cache the whole file for next time
      return res;
    } catch (err) {
      if (req.mode === 'navigate') { const page = await cache.match('404.html'); if (page) return page; }
      throw err;
    }
  })());
});
`;
fs.writeFileSync(path.join(DIST, 'sw.js'), sw);
const mb = n => (n / 1e6).toFixed(1) + ' MB';
const size = list => list.reduce((s, f) => s + fs.statSync(path.join(DIST, f)).size, 0);
console.log(`postbuild: sw.js written (cache ${version}). core ${core.length} files ${mb(size(core))}, maps ${maps.length} files ${mb(size(maps))}, total dist ${all.length} files ${mb(size(all))}`);
